pub fn drawChar(buffer: []u8, width: u32, x: u32, y: u32, char: u8, scale: u32, r: u8, g: u8, b: u8) void {
    if (char < 32 or char > 90) return;
    const idx = (@as(usize, char) - 32) * 7;
    var row: u32 = 0;
    while (row < 7) : (row += 1) {
        const bits = font5x7[idx + row];
        var col: u32 = 0;
        while (col < 5) : (col += 1) {
            if (bits & (@as(u8, 1) << @intCast(4 - col)) != 0) {
                // Draw scaled pixel
                var sy: u32 = 0;
                while (sy < scale) : (sy += 1) {
                    var sx: u32 = 0;
                    while (sx < scale) : (sx += 1) {
                        const px = x + col * scale + sx;
                        const py = y + row * scale + sy;
                        if (px < width and py < (buffer.len / (width * 4))) {
                            const i = (py * width + px) * 4;
                            if (i + 3 < buffer.len) {
                                buffer[i] = r;
                                buffer[i + 1] = g;
                                buffer[i + 2] = b;
                            }
                        }
                    }
                }
            }
        }
    }
}

pub fn drawText(buffer: []u8, width: u32, x: u32, y: u32, text: []const u8, scale: u32, r: u8, g: u8, b: u8) void {
    var cx = x;
    for (text) |c| {
        if (c == ' ') {
            cx += 4 * scale;
            continue;
        }
        if (c < 32 or c > 126) {
            cx += 4 * scale;
            continue;
        }
        drawChar(buffer, width, cx, y, c, scale, r, g, b);
        cx += 6 * scale;
    }
}
